"""One naming convention for every constraint and index.

Adopted while the schema holds three tables. Constraint names are read by Alembic
when it compares metadata to the database, so a convention introduced after ten
tables exist becomes a rename migration across all ten — which is why this lands
now rather than later.

Applied by import: `app.models` and `app.modules` both import this module before
defining any table, and `app.db_models` (the registry Alembic reads) imports both.
"""

from typing import Final

from sqlalchemy import Index, MetaData, PrimaryKeyConstraint, UniqueConstraint
from sqlmodel import SQLModel

NAMING_CONVENTION: Final[dict[str, str]] = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

SQLModel.metadata.naming_convention = NAMING_CONVENTION


def _leading(columns: list[str], width: int) -> frozenset[str]:
    return frozenset(columns[:width])


def index_foreign_keys(metadata: MetaData) -> list[Index]:
    """Give every foreign key an index whose leading columns are exactly its own.

    Postgres indexes the referenced side of a foreign key, never the referencing side, so without
    one a join from parent to child, and the RESTRICT check a parent's delete runs, scan the child
    table. Called once by `app.db_models` after every model is registered, so a foreign key added
    later is indexed by the same autogenerated migration that adds it. An index, unique constraint
    or primary key that already leads with the key's columns (in any order) counts; nothing is
    added twice. Names are `ix_<table>_<columns>`, cut to Postgres's 63 characters.
    """
    added: list[Index] = []
    for table in list(metadata.tables.values()):
        covering = [
            [column.name for column in index.columns] for index in table.indexes
        ] + [
            [column.name for column in constraint.columns]
            for constraint in table.constraints
            if isinstance(constraint, (UniqueConstraint, PrimaryKeyConstraint))
        ]
        for foreign_key in table.foreign_key_constraints:
            columns = [column.name for column in foreign_key.columns]
            wanted = frozenset(columns)
            if any(_leading(existing, len(columns)) == wanted for existing in covering):
                continue
            name = f"ix_{table.name}_{'_'.join(columns)}"[:63]
            added.append(Index(name, *(table.c[column] for column in columns)))
            covering.append(columns)
    return added
